// To print a text on to screen
// we can use JShell (Java Shell) is the tool, we'll be using to achieve this,
class HelloWorld{
	public static void main(String[] args){
		//The Following line is known as `statement`
		System.out.println("Hello World");
		//What is `statement`?
		/*
			A complete command to be executed.
			It can include one or more `expressions`.
			HERE: Command to display some text on console screen using Java Syntax.
			What to be diplayed is specified in quotes "".
		*/
	}
}

